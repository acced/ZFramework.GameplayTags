using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Security.Cryptography;
using System.Text;
using UnityEditor;
using UnityEditor.Build;
using UnityEditor.Build.Reporting;

namespace GameplayTags.Editor
{
    /// <summary>
    /// Opt-in, two-pass Player registration. The current Player compilation is the
    /// declaration source; Editor reflection is never used to approximate it.
    /// </summary>
    public static class GameplayTagRegistryGenerator
    {
        public const string OutputPath = "Assets/GameplayTags.Generated.cs";
        private const string Header = "// Generated by GameplayTagRegistryGenerator.";

        [MenuItem("Tools/Gameplay Tags/Generate Player Registry")]
        public static void Generate()
        {
            EnsureOwnedOutput();
            if (!File.Exists(OutputPath))
            {
                File.WriteAllText(OutputPath, GenerateSource(Array.Empty<GameplayTagRegistration>()), new UTF8Encoding(false));
                AssetDatabase.ImportAsset(OutputPath);
            }
            UnityEngine.Debug.Log("Player registry enabled. Build your actual target/configuration. If declarations changed, " +
                "the build writes their exact table and stops; allow script compilation and build again. " +
                "Call GameplayTags.Generated.GameplayTagRegistry.Initialize() before caching tags. " +
                "No automatic startup callback is installed.");
        }

        /// <summary>
        /// Export from actual compiled Player assemblies (including managed plugins).
        /// Returns true only when both the source and the table compiled into those
        /// assemblies already match. False means source was refreshed and must be compiled.
        /// Custom build pipelines may use this same boundary before linking/stripping.
        /// </summary>
        public static bool GenerateFromPlayerAssemblies(IEnumerable<string> playerAssemblyPaths)
        {
            EnsureOwnedOutput();
            GameplayTagPlayerMetadata.Snapshot snapshot = GameplayTagPlayerMetadata.Read(playerAssemblyPaths);
            GameplayTagRegistration[] ordered = Order(snapshot.Registrations);
            string fingerprint = Fingerprint(ordered);
            string source = GenerateOrderedSource(ordered, fingerprint);
            bool sourceMatches = File.Exists(OutputPath) && File.ReadAllText(OutputPath) == source;
            if (!sourceMatches) File.WriteAllText(OutputPath, source, new UTF8Encoding(false));
            return sourceMatches && snapshot.RegistryDefinitions == 1 && snapshot.CompiledFingerprint == fingerprint;
        }

        public static string GenerateSource(IEnumerable<GameplayTagRegistration> registrations)
        {
            GameplayTagRegistration[] ordered = Order(registrations);
            return GenerateOrderedSource(ordered, Fingerprint(ordered));
        }

        private static GameplayTagRegistration[] Order(IEnumerable<GameplayTagRegistration> registrations) =>
            registrations.OrderBy(t => t.Name, StringComparer.Ordinal)
                .ThenBy(t => t.Description, StringComparer.Ordinal).ThenBy(t => (int)t.Flags).ToArray();

        private static string Fingerprint(GameplayTagRegistration[] registrations)
        {
            using var stream = new MemoryStream();
            using (var writer = new BinaryWriter(stream, Encoding.UTF8, true))
            {
                writer.Write(registrations.Length);
                foreach (GameplayTagRegistration tag in registrations)
                {
                    WriteNullable(writer, tag.Name);
                    WriteNullable(writer, tag.Description);
                    writer.Write((int)tag.Flags);
                }
            }
            using var sha = SHA256.Create();
            return BitConverter.ToString(sha.ComputeHash(stream.ToArray())).Replace("-", "").ToLowerInvariant();
        }

        private static void WriteNullable(BinaryWriter writer, string value)
        {
            writer.Write(value != null);
            if (value != null) writer.Write(value);
        }

        private static string GenerateOrderedSource(GameplayTagRegistration[] registrations, string fingerprint)
        {
            var source = new StringBuilder();
            source.Append(Header).Append(" Do not edit.\n")
                .Append("// Player declarations are read after actual Player compilation, before stripping.\n")
                .Append("// Call Initialize once from your boot sequence, before any tag lookup.\n")
                .Append("namespace GameplayTags.Generated\n{\n    public static class GameplayTagRegistry\n    {\n")
                .Append("        public const string DeclarationFingerprint = ").Append(Literal(fingerprint)).Append(";\n")
                .Append("        public static void Initialize()\n        {\n")
                .Append("#if UNITY_EDITOR\n            GameplayTagManager.InitializeIfNeeded();\n")
                .Append("#else\n            GameplayTagManager.Initialize(CreateRegistrations());\n#endif\n        }\n")
                .Append("        public static GameplayTagRegistration[] CreateRegistrations() => new GameplayTagRegistration[]\n        {\n");
            foreach (GameplayTagRegistration tag in registrations)
                source.Append("            new GameplayTagRegistration(").Append(Literal(tag.Name)).Append(", ")
                    .Append(Literal(tag.Description)).Append(", (GameplayTagFlags)").Append((int)tag.Flags).Append("),\n");
            source.Append("        };\n    }\n}\n");
            return source.ToString();
        }

        // Build-time file ownership is not a runtime parameter policy: never overwrite
        // an application-authored script at the generator's reserved output location.
        private static void EnsureOwnedOutput()
        {
            if (File.Exists(OutputPath) && !File.ReadAllText(OutputPath).StartsWith(Header, StringComparison.Ordinal))
                throw new InvalidOperationException("Not a generated file: " + OutputPath);
        }

        private static string Literal(string value)
        {
            if (value == null) return "null";
            var result = new StringBuilder("\"");
            foreach (char c in value)
            {
                if (c == '\\' || c == '"') result.Append('\\').Append(c);
                else if (c < ' ' || c == '\u2028' || c == '\u2029') result.Append("\\u").Append(((int)c).ToString("x4"));
                else result.Append(c);
            }
            return result.Append('"').ToString();
        }
    }

    internal sealed class GameplayTagRegistryBuildCheck : IPostBuildPlayerScriptDLLs
    {
        public int callbackOrder => int.MaxValue;

        public void OnPostBuildPlayerScriptDLLs(BuildReport report)
        {
            if (!File.Exists(GameplayTagRegistryGenerator.OutputPath)) return;
            // BuildReport is the actual target/plugin/define selection, not the Editor
            // AppDomain or a guess based on currently imported assemblies. Native DLLs
            // are filtered by the metadata reader, not by platform-dependent role text.
            var paths = report.GetFiles().Where(f => f.path.EndsWith(".dll", StringComparison.OrdinalIgnoreCase))
                .Select(f => f.path);
            if (!GameplayTagRegistryGenerator.GenerateFromPlayerAssemblies(paths))
                throw new BuildFailedException("Gameplay tag Player declarations changed. Updated " +
                    GameplayTagRegistryGenerator.OutputPath + ". Let Unity compile the generated script and build again " +
                    "with the same target and defines. The current build was stopped rather than shipping a stale table.");
        }
    }
}
