using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Security.Cryptography;
using System.Text;
using UnityEditor;
using UnityEditor.Build;
using UnityEditor.Build.Reporting;

namespace GameplayTags.Editor
{
    /// <summary>
    /// Generate runtime code from the project ScriptableObject configuration.
    /// Build validation checks the configuration before Player script compilation.
    /// </summary>
    public static class GameplayTagRegistryGenerator
    {
        public const string OutputDirectory = "Assets/GameplayTags.Generated";
        public const string OutputPath = OutputDirectory + "/GameplayTags.Generated.cs";
        public const string AssemblyName = "ZFramework.GameplayTags.Generated";
        public const string AssemblyDefinitionPath = OutputDirectory + "/" + AssemblyName + ".asmdef";
        private const string Header = "// Generated by GameplayTagRegistryGenerator.";
        // Include the generator format as well as tag data in the fingerprint.
        private const int GeneratedFormatVersion = 5;

        [MenuItem("Tools/Gameplay Tags/Generate Player Registry")]
        public static void Generate()
        {
            GameplayTagSettings settings = GameplayTagSettings.Find();
            if (settings == null)
                throw new InvalidOperationException("Create a tag configuration in Tools/Gameplay Tags/Tag Settings first.");
            GameplayTagRegistration[] registrations = settings.CreateRegistrations();
            string source = GenerateSource(registrations);
            AssetDatabase.SaveAssets();
            bool changed = EnsureOutputLayout();
            if (!File.Exists(OutputPath) || File.ReadAllText(OutputPath) != source)
            {
                File.WriteAllText(OutputPath, source, new UTF8Encoding(false));
                changed = true;
            }
            if (changed) AssetDatabase.Refresh();
            UnityEngine.Debug.Log("Generated registry and fields from " + registrations.Length +
                " configured tags: " + OutputPath);
        }

        public static void ValidateGeneratedOutput()
        {
            GameplayTagSettings settings = GameplayTagSettings.Find();
            if (settings == null)
            {
                if (File.Exists(OutputPath))
                    throw new InvalidOperationException("Generated registry exists but its GameplayTagSettings configuration is missing.");
                return; // Explicit runtime initialization remains usable without the Editor workflow.
            }
            string expected = GenerateSource(settings.CreateRegistrations());
            if (!File.Exists(OutputPath) || File.ReadAllText(OutputPath) != expected ||
                !File.Exists(AssemblyDefinitionPath))
                throw new InvalidOperationException("Gameplay tag configuration and generated code differ. " +
                    "Use Tools/Gameplay Tags/Generate Player Registry, wait for compilation, then build again.");
        }

        public static string GenerateSource(IEnumerable<GameplayTagRegistration> registrations)
        {
            GameplayTagRegistration[] ordered = Order(registrations);
            return GenerateOrderedSource(ordered, Fingerprint(ordered));
        }

        private static GameplayTagRegistration[] Order(IEnumerable<GameplayTagRegistration> registrations) =>
            registrations.OrderBy(t => t.Name, StringComparer.Ordinal)
                .ThenBy(t => t.Description, StringComparer.Ordinal).ToArray();

        private static string Fingerprint(GameplayTagRegistration[] registrations)
        {
            using var stream = new MemoryStream();
            using (var writer = new BinaryWriter(stream, Encoding.UTF8, true))
            {
                writer.Write(GeneratedFormatVersion);
                writer.Write(registrations.Length);
                foreach (GameplayTagRegistration tag in registrations)
                {
                    WriteNullable(writer, tag.Name);
                    WriteNullable(writer, tag.Description);
                }
            }
            using var sha = SHA256.Create();
            return BitConverter.ToString(sha.ComputeHash(stream.ToArray())).Replace("-", "").ToLowerInvariant();
        }

        private static void WriteNullable(BinaryWriter writer, string value)
        {
            writer.Write(value != null);
            if (value != null) writer.Write(value);
        }

        private static string GenerateOrderedSource(GameplayTagRegistration[] registrations, string fingerprint)
        {
            var source = new StringBuilder();
            source.Append(Header).Append(" Do not edit.\n")
                .Append("// Generated from GameplayTagSettings. Editor and Player use the same registration data.\n")
                .Append("// Automatically initialized; Initialize remains available for explicit boot sequences.\n")
                .Append("namespace GameplayTags.Generated\n{\n    public static class GameplayTagRegistry\n    {\n")
                .Append("        public const string DeclarationFingerprint = ").Append(Literal(fingerprint)).Append(";\n")
                .Append("#if UNITY_5_3_OR_NEWER\n        [global::UnityEngine.Scripting.Preserve]\n#endif\n")
                .Append("        public static void Initialize()\n        {\n")
                .Append("            if (!GameplayTagManager.IsInitialized)\n                GameplayTagManager.Initialize(CreateRegistrations());\n        }\n")
                .Append("#if UNITY_5_3_OR_NEWER && !GAMEPLAY_TAGS_MANUAL_INITIALIZATION\n")
                .Append("        [global::UnityEngine.RuntimeInitializeOnLoadMethod(global::UnityEngine.RuntimeInitializeLoadType.SubsystemRegistration)]\n")
                .Append("        private static void AutoInitialize() => Initialize();\n#endif\n")
                .Append("        public static GameplayTagRegistration[] CreateRegistrations() => new GameplayTagRegistration[]\n        {\n");
            foreach (GameplayTagRegistration tag in registrations)
                source.Append("            new GameplayTagRegistration(").Append(Literal(tag.Name)).Append(", ")
                    .Append(Literal(tag.Description)).Append("),\n");
            source.Append("        };\n");
            AppendTagFields(source, registrations);
            source.Append("    }\n}\n");
            return source.ToString();
        }

        private static void AppendTagFields(StringBuilder source, GameplayTagRegistration[] registrations)
        {
            // Include implicit parents and emit each name once, even for duplicate declarations.
            var names = new SortedSet<string>(StringComparer.Ordinal);
            foreach (GameplayTagRegistration registration in registrations)
            {
                GameplayTagUtility.ValidateName(registration.Name);
                foreach (string name in GameplayTagUtility.GetHierarchyNames(registration.Name))
                    names.Add(name);
            }

            source.Append("\n        /// <summary>Cached handles, including implicit parents. Resolved on first access.</summary>\n")
                .Append("        public static class Tags\n        {\n");
            foreach (string name in names)
                source.Append("            public static readonly global::GameplayTags.GameplayTag ").Append(FieldIdentifier(name)).Append(";\n");

            // An explicit constructor prevents beforefieldinit eager name lookups.
            source.Append("\n            static Tags()\n            {\n");
            foreach (string name in names)
                source.Append("                ").Append(FieldIdentifier(name))
                    .Append(" = global::GameplayTags.GameplayTagManager.RequestTag(").Append(Literal(name)).Append(");\n");
            source.Append("            }\n        }\n");
        }

        // Prefix-free escaping keeps identifiers stable when new tags are added:
        // dot -> __, literal underscore -> _u, other UTF-16 characters -> _xHHHH.
        // Numeric starts and the containing type name receive reserved prefixes.
        private static string FieldIdentifier(string name)
        {
            var identifier = new StringBuilder("@"); // Also supports C# keywords such as "class".
            if (name[0] >= '0' && name[0] <= '9') identifier.Append("_n");
            if (name == "Tags") identifier.Append("_r");
            foreach (char c in name)
            {
                if (c == '.') identifier.Append("__");
                else if (c == '_') identifier.Append("_u");
                else if ((c >= 'A' && c <= 'Z') || (c >= 'a' && c <= 'z') || (c >= '0' && c <= '9'))
                    identifier.Append(c);
                else identifier.Append("_x").Append(((int)c).ToString("X4"));
            }
            return identifier.ToString();
        }

        private static bool EnsureOutputLayout()
        {
            // Only overwrite files owned by this generator.
            if (File.Exists(OutputPath) && !File.ReadAllText(OutputPath).StartsWith(Header, StringComparison.Ordinal))
                throw new InvalidOperationException("Not a generated file: " + OutputPath);

            Directory.CreateDirectory(OutputDirectory);
            bool changed = false;
            if (!File.Exists(AssemblyDefinitionPath))
            {
                File.WriteAllText(AssemblyDefinitionPath,
                    "{\n  \"name\": \"" + AssemblyName + "\",\n" +
                    "  \"rootNamespace\": \"GameplayTags.Generated\",\n" +
                    "  \"references\": [\"ZFramework.GameplayTags\"],\n" +
                    "  \"autoReferenced\": true\n}\n", new UTF8Encoding(false));
                changed = true;
            }
            return changed;
        }

        private static string Literal(string value)
        {
            if (value == null) return "null";
            var result = new StringBuilder("\"");
            foreach (char c in value)
            {
                if (c == '\\' || c == '"') result.Append('\\').Append(c);
                else if (c < ' ' || c == '\u2028' || c == '\u2029') result.Append("\\u").Append(((int)c).ToString("x4"));
                else result.Append(c);
            }
            return result.Append('"').ToString();
        }
    }

    internal sealed class GameplayTagRegistryBuildCheck : IPreprocessBuildWithReport
    {
        public int callbackOrder => -10000;
        public void OnPreprocessBuild(BuildReport report)
        {
            try { GameplayTagRegistryGenerator.ValidateGeneratedOutput(); }
            catch (Exception exception) { throw new BuildFailedException(exception.Message); }
        }
    }
}
